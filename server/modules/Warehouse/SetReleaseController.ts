function summarizeReleaseBatches(items: unknown): string {
  return extractComponentBatchesFromReleaseRecord({ items })
    .map((allocation) => {
      const batches = (allocation.batches ?? [])
        .map((batch) => `${batch.batchNumber || batch.batchId}×${batch.quantity}`)
        .join(', ');
      return `${allocation.sku}: ${batches}`;
    })
    .join('; ');
}

function preserveReleaseItemMeta(existingItems: unknown, nextItems: any[]): any[] {
  const first = Array.isArray(existingItems) ? existingItems[0] : null;
  const meta = first && typeof first === 'object' ? first as Record<string, unknown> : {};
  return nextItems.map((item, index) => {
    if (index !== 0 || !item || typeof item !== 'object') return item;
    return {
      ...item,
      ...(meta.kit_output_batch ? { kit_output_batch: meta.kit_output_batch } : {}),
      ...(meta.dilovod_remark ? { dilovod_remark: meta.dilovod_remark } : {}),
      ...(meta.dilovod_send_error ? { dilovod_send_error: meta.dilovod_send_error } : {}),
      ...(meta.correction_session_id ? { correction_session_id: meta.correction_session_id } : {}),
    };
  });
}

function buildReleaseUpdateDiff(
  before: {
    operDate: Date;
    comment: string | null;
    quantity: number;
    setSku: string | null;
    batches?: string;
    storageId?: string | null;
    firmId?: string | null;
  },
  after: {
    operDate: Date;
    comment: string | null;
    quantity: number;
    setSku: string | null;
    batches?: string;
    storageId?: string | null;
    firmId?: string | null;
  },
) {
  const changes: Array<{ field: string; from: unknown; to: unknown }> = [];
  const push = (field: string, from: unknown, to: unknown) => {
    if (String(from ?? '') !== String(to ?? '')) {
      changes.push({ field, from, to });
    }
  };
  const sameInstant = Math.abs(before.operDate.getTime() - after.operDate.getTime()) < 1000;
  if (!sameInstant) {
    changes.push({ field: 'operDate', from: before.operDate.toISOString(), to: after.operDate.toISOString() });
  }
  push('comment', before.comment, after.comment);
  push('quantity', before.quantity, after.quantity);
  push('setSku', before.setSku, after.setSku);
  push('batches', before.batches, after.batches);
  push('storageId', before.storageId, after.storageId);
  push('firmId', before.firmId, after.firmId);
  return changes;
}

