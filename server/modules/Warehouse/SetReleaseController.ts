async function prepareReleaseHistoryPayload(params: {
  items: any[];
  componentBatches: ReleaseComponentAllocation[];
  remark: unknown;
  comment: unknown;
  operationType?: unknown;
  operDate?: unknown;
  date?: unknown;
  correctionSessionId?: unknown;
}): Promise<ReleaseHistoryPayload> {
  const {
    items,
    componentBatches,
    remark,
    comment,
    operationType,
    operDate,
    date,
    correctionSessionId,
  } = params;

  const skus = Array.from(new Set(items.map((it: any) => String(it.set_sku || it.setSku || it.sku || '').trim()).filter((s: string) => s)));
  let nameMap: Record<string, string> = {};
  if (skus.length > 0) {
    const found = await catalogOpsLookup.getBySkus(skus);
    for (const product of catalogOpsLookup.listUnique(found)) {
      nameMap[String(product.sku)] = product.name || '';
    }
  }

  const normalizedItems = normalizeReleaseHistoryItems(items);
  const inheritedCorrectionSession = extractCorrectionSessionIdFromItems(normalizedItems);
  let resolvedCorrectionSession = correctionSessionId != null && String(correctionSessionId).trim() !== ''
    ? String(correctionSessionId).trim()
    : inheritedCorrectionSession;

  const totalQuantityPreview = Number(
    normalizedItems.reduce((acc: number, it: any) => acc + (Number(it.quantity) || 0), 0),
  ) || 0;
  const historyCommentPreview = buildReleaseHistoryComment(remark, comment);
  // Якщо коментар/REBATCH вказує на коригування, а сесії немає — створюємо, щоб історія не губила маркер.
  if (
    !resolvedCorrectionSession
    && isReleaseBatchCorrection({
      comment: historyCommentPreview,
      setSku: normalizedItems[0]?.set_sku ?? normalizedItems[0]?.setSku,
      items: normalizedItems,
    })
  ) {
    resolvedCorrectionSession = createCorrectionSessionId();
  }

  const itemsWithNames = normalizedItems.map((it: any) => {
    const sku = String(it.set_sku || it.setSku || it.sku || '').trim();
    const mergedSnapshot = mergeBatchesIntoComponentsSnapshot(
      it.components_snapshot ?? it.componentsSnapshot,
      componentBatches,
    );
    return {
      ...it,
      name: it.name ?? nameMap[sku] ?? null,
      components_snapshot: mergedSnapshot,
      component_batches: componentBatches,
      correction_session_id: resolvedCorrectionSession,
    };
  });

  const totalQuantity = totalQuantityPreview;
  const historyComment = historyCommentPreview;
  const resolvedOperationType = String(operationType ?? 'kit').trim() === 'unkit' ? 'unkit' : 'kit';
  const resolvedOperDate = parseLocalDate(operDate ?? date) ?? new Date();

  return {
    itemsWithNames,
    totalQuantity,
    historyComment,
    resolvedOperationType,
    resolvedOperDate,
    setSku: itemsWithNames[0]?.set_sku ?? null,
  };
}

