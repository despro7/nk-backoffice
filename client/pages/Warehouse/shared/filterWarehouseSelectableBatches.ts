import type { ReturnBatch } from '../WarehouseReturns/WarehouseReturnsTypes';
import {
  canSetTpGoodsGoodPart,
  isAutoGeneratedSystemBatch,
} from '@shared/utils/dilovodBatchId';

/**
 * Партії для dropdown списання/оприбуткування.
 * Віртуальні document-партії з балансу залишаємо (ручний вибір для зведення);
 * локальні `virtual:` і системні auto-batch — ні.
 * Реальні catalogs.goodParts йдуть першими (зручніше для автовибору).
 */
export function filterWarehouseSelectableBatches(batches: ReturnBatch[]): ReturnBatch[] {
  const filtered = batches.filter((batch) => {
    const batchId = String(batch.batchId ?? '').trim();
    if (batchId.startsWith('virtual:')) return false;
    const label = String(batch.batchNumber ?? batch.batchId ?? '').trim();
    if (isAutoGeneratedSystemBatch(label)) return false;
    return Boolean(batchId);
  });

  return filtered.sort((left, right) => {
    const leftReal = canSetTpGoodsGoodPart({
      batchId: left.batchId,
      batchNumber: left.batchNumber,
    }) ? 0 : 1;
    const rightReal = canSetTpGoodsGoodPart({
      batchId: right.batchId,
      batchNumber: right.batchNumber,
    }) ? 0 : 1;
    return leftReal - rightReal;
  });
}

/**
 * Автопідстановка: перша реальна catalogs.goodParts.
 * Якщо реальних немає — лише коли партія одна (зафіксований єдиний вибір), інакше null (ручний вибір).
 */
export function pickDefaultRealWarehouseBatch(batches: ReturnBatch[]): ReturnBatch | null {
  for (const batch of batches) {
    if (canSetTpGoodsGoodPart({
      batchId: batch.batchId,
      batchNumber: batch.batchNumber,
    })) {
      return batch;
    }
  }
  return batches.length === 1 ? batches[0] : null;
}
