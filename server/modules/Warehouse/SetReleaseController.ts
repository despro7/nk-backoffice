type DirectSetComponent = {
  sku: string;
  name: string | null;
  quantity: number;
};

function parseSetComponents(rawSet: unknown): Array<{ id?: string | number | null; sku?: string | number | null; quantity?: number | string | null; name?: string | null }> {
  if (Array.isArray(rawSet)) {
    return rawSet;
  }

  if (typeof rawSet === 'string') {
    try {
      const parsed = JSON.parse(rawSet);
      return Array.isArray(parsed) ? parsed : [];
    } catch (error) {
      console.warn('[SetRelease] Failed to parse set JSON:', error);
      return [];
    }
  }

  return [];
}

function normalizeDirectComponentsFromSnapshot(snapshot: unknown, parentQty: number): DirectSetComponent[] {
  if (!Array.isArray(snapshot) || parentQty <= 0) {
    return [];
  }

  const components: DirectSetComponent[] = [];
  for (const component of snapshot) {
    if (!component) continue;
    const rawSku = component.id ?? component.sku ?? component.code ?? null;
    const sku = String(rawSku ?? '').trim();
    if (!sku) continue;

    const quantity = Number(component.quantity ?? component.qty ?? 1);
    if (!Number.isFinite(quantity) || quantity <= 0) continue;

    components.push({
      sku,
      name: component.name ?? component.title ?? null,
      quantity: quantity * parentQty,
    });
  }

  return components;
}

async function collectFirstLevelComponents(items: ReleaseSetSourceItem[]): Promise<Record<string, DirectSetComponent>> {
  const aggregated: Record<string, DirectSetComponent> = {};

  for (const item of items) {
    const sku = String(item.set_sku ?? item.setSku ?? item.sku ?? '').trim();
    const quantity = Number(item.quantity ?? 0);
    if (!sku || !Number.isFinite(quantity) || quantity <= 0) {
      continue;
    }

    let directComponents = normalizeDirectComponentsFromSnapshot(item.components_snapshot, quantity);

    if (directComponents.length === 0) {
      const product = await catalogOpsLookup.getBySku(sku);
      const setData = parseSetComponents(product?.set);
      if (setData.length === 0) {
        if (product?.dilovodId) {
          if (!aggregated[sku]) {
            aggregated[sku] = { sku, name: product?.name ?? null, quantity: 0 };
          }
          aggregated[sku].quantity += quantity;
        }
        continue;
      }

      directComponents = setData
        .map((component) => {
          const componentSku = String(component.id ?? component.sku ?? '').trim();
          if (!componentSku) return null;
          const componentQty = Number(component.quantity ?? 1);
          if (!Number.isFinite(componentQty) || componentQty <= 0) return null;
          return {
            sku: componentSku,
            name: component.name ?? null,
            quantity: componentQty * quantity,
          };
        })
        .filter((component): component is DirectSetComponent => component !== null);
    }

    for (const component of directComponents) {
      if (!aggregated[component.sku]) {
        aggregated[component.sku] = { sku: component.sku, name: component.name ?? null, quantity: 0 };
      }
      if (!aggregated[component.sku].name && component.name) {
        aggregated[component.sku].name = component.name;
      }
      aggregated[component.sku].quantity += component.quantity;
    }
  }

  return aggregated;
}

function isSelectableReleaseBatch(
  batch: Pick<ReleaseComponentBatch, 'batchId' | 'batchNumber' | 'quantity'>,
  options?: { excludeAutoGenerated?: boolean },
): boolean {
  const batchId = String(batch?.batchId ?? '').trim();
  const quantity = Number(batch?.quantity ?? 0);
  if (!batchId || !Number.isFinite(quantity) || quantity <= 0) return false;
  if (options?.excludeAutoGenerated === false) return true;
  const label = batch?.batchNumber ? String(batch.batchNumber).trim() : batchId;
  return !isAutoGeneratedSystemBatch(label);
}

function parseComponentBatches(
  raw: unknown,
  options?: { excludeAutoGenerated?: boolean },
): ReleaseComponentAllocation[] {
  if (!Array.isArray(raw)) return [];
  return raw
    .map((allocation) => {
      const sku = String(allocation?.sku ?? '').trim();
      const batches = Array.isArray(allocation?.batches)
        ? allocation.batches
            .map((batch: ReleaseComponentBatch) => ({
              batchId: String(batch?.batchId ?? '').trim(),
              batchNumber: batch?.batchNumber ? String(batch.batchNumber).trim() : undefined,
              quantity: Number(batch?.quantity ?? 0),
            }))
            .filter((batch) => isSelectableReleaseBatch(batch, options))
        : [];
      if (!sku || batches.length === 0) return null;
      return { sku, batches };
    })
    .filter((allocation): allocation is ReleaseComponentAllocation => allocation !== null);
}

function extractComponentBatchesFromReleaseRecord(record: {
  items?: unknown;
}): ReleaseComponentAllocation[] {
  const items = Array.isArray(record.items) ? record.items : [];
  const firstItem = items[0];
  if (!firstItem || typeof firstItem !== 'object') return [];

  const direct = parseComponentBatches((firstItem as { component_batches?: unknown }).component_batches);
  if (direct.length > 0) return direct;

  const snapshot = (firstItem as { components_snapshot?: unknown }).components_snapshot;
  if (!Array.isArray(snapshot)) return [];

  const allocations: ReleaseComponentAllocation[] = [];
  for (const component of snapshot) {
    const sku = String(component?.id ?? component?.sku ?? component?.code ?? '').trim();
    const batches = Array.isArray(component?.batches)
      ? component.batches
          .map((batch: ReleaseComponentBatch) => ({
            batchId: String(batch?.batchId ?? '').trim(),
            batchNumber: batch?.batchNumber ? String(batch.batchNumber).trim() : undefined,
            quantity: Number(batch?.quantity ?? 0),
          }))
          .filter(isSelectableReleaseBatch)
      : [];
    if (sku && batches.length > 0) {
      allocations.push({ sku, batches });
    }
  }
  return allocations;
}

function shouldExcludeAutoGeneratedBatches(correctionSessionId: unknown): boolean {
  return !String(correctionSessionId ?? '').trim();
}

