async function syncWarehouseReleaseToDilovod(input: {
  record: {
    id: number;
    dilovodDocId: string | null;
    items: unknown;
    storageId: string | null;
    firmId: string | null;
    operationType: string;
    internalDocNumber: string | null;
  };
  operDate: Date;
  quantity: number;
  setSku: string | null;
  remarkNote: string;
}): Promise<{ success: boolean; error?: string; dilovodResponse?: unknown; remark?: string }> {
  const dilovodDocId = input.record.dilovodDocId != null ? String(input.record.dilovodDocId).trim() : '';
  if (!dilovodDocId) {
    return { success: true };
  }

  const setSku = String(input.setSku ?? '').trim();
  const resolvedKitGood = await resolveKitGoodId(setSku, undefined);
  if (!resolvedKitGood) {
    return { success: false, error: 'Не вдалося визначити ID набору в Dilovod для оновлення' };
  }

  const sourceItems = releaseItemsToSendSource(input.record.items);
  const componentBatches = extractComponentBatchesFromReleaseRecord({ items: input.record.items });
  const expandedComponents = await collectFirstLevelComponents(sourceItems);
  const { loadDilovodWarehouseDefaults } = await import('../../services/dilovod/DilovodWarehouseDefaults.js');
  const warehouseDefaults = await loadDilovodWarehouseDefaults();

  const expandedList = Object.values(expandedComponents);
  const skus = expandedList.map((component) => component.sku).filter(Boolean);
  const found = skus.length ? await catalogOpsLookup.getBySkus(skus) : new Map();
  const skuToProduct = new Map(catalogOpsLookup.listUnique(found).map((product) => [product.sku, product]));
  const skuToDilovodId = new Map<string, string>();
  const skuToHasNestedSet = new Map<string, boolean>();

  for (const [sku, product] of skuToProduct.entries()) {
    if (!product?.dilovodId) continue;
    skuToDilovodId.set(sku, product.dilovodId);
    const hasNestedSet = Array.isArray(product.set)
      ? product.set.length > 0
      : typeof product.set === 'string'
        ? String(product.set).trim().length > 0
        : Boolean(product.set);
    skuToHasNestedSet.set(sku, hasNestedSet);
  }

  const { tpGoods } = buildTpGoodsFromBatches(
    expandedList,
    skuToDilovodId,
    skuToHasNestedSet,
    componentBatches,
    warehouseDefaults,
  );

  const storedKitBatch = extractStoredKitOutputBatch(input.record.items);
  const previousRemark = extractDilovodRemarkFromReleaseItems(input.record.items);
  const remark = appendWarehouseReleaseDilovodRemark(previousRemark, input.remarkNote);
  const resolvedDocMode = String(input.record.operationType ?? '').trim() === 'unkit'
    ? SET_RELEASE_DOC_MODE_UNKIT
    : SET_RELEASE_DOC_MODE_KIT;

  const payload: Record<string, unknown> = {
    saveType: 2,
    header: {
      id: dilovodDocId,
      date: formatLocalDate(input.operDate),
      firm: input.record.firmId,
      storage: input.record.storageId,
      posted: 1,
      accCosts: warehouseDefaults.setAccountId,
      docMode: resolvedDocMode,
      kitGood: resolvedKitGood,
      kitQty: input.quantity,
      ...(storedKitBatch?.batchId ? { kitGoodPart: Number(storedKitBatch.batchId) } : {}),
      remark,
    },
    tableParts: { tpGoods },
  };

  const exportResult = await dilovodExportFlowService.send({
    payload,
    dryRun: false,
    warnings: [],
    label: '[SetRelease][patch]',
  });

  if (!exportResult.success) {
    const rawError = exportResult.error || exportResult.dilovodResponse?.error || exportResult.dilovodResponse?.message || 'Dilovod error';
    const message = exportResult.dilovodResponse ? getDilovodExportErrorMessage(exportResult.dilovodResponse) : String(rawError);
    return { success: false, error: message, dilovodResponse: exportResult.dilovodResponse };
  }

  return { success: true, dilovodResponse: exportResult.dilovodResponse, remark };
}

