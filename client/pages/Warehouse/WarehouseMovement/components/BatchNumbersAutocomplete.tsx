import { useMemo } from 'react';
import { Drawer, DrawerContent, DrawerHeader, DrawerBody, DrawerFooter, Button } from '@heroui/react';
import { motion } from 'framer-motion';
import { DynamicIcon } from 'lucide-react/dynamic';
import {
  isProductionOrderVirtualBatch,
  PRODUCTION_ORDER_BATCH_WARNING,
} from '@shared/utils/dilovodBatchId';
import { useDebug } from '@/contexts/debug-context';
import type { BatchNumber } from '../hooks/useBatchNumbers';
import { resolveStorageIconClass } from '../storageDisplay';
import { QtyPills } from '../../shared/QtyPills';
import { breakdownStockPortions } from '../../WarehouseMovementMob/WarehouseMovementMobUtils';

interface BatchNumbersAutocompleteProps {
  batches: BatchNumber[];
  isOpen: boolean;
  isLoading: boolean;
  selectedBatch: string;
  selectedStorage: string;
  selectedDateTime?: Date;
  /** ID складу-джерела (напрямок переміщення) — для підказки у заголовку */
  sourceStorage?: string;
  /** Назва складу-джерела для відображення у заголовку (опціонально) */
  sourceStorageName?: string;
  /**
   * Режим каталогу: партії з ГП + малого складу.
   * Змінює текст підказки; у кожному рядку вже є помітка складу зберігання.
   */
  includeAllStorages?: boolean;
  /** Ключі вже доданих партій у форматі "batchId:storage" (крім поточної редагованої) */
  addedBatchKeys?: Set<string>;
  /** Порцій у коробці — для віджета коробки + розсип під залишком */
  portionsPerBox?: number | null;
  /** Показувати партії з від'ємними залишками (коригування обліку) */
  includeNonPositiveQty?: boolean;
  /** API: balance з qty≠0 (переміщення), без каталожних нульових */
  includeNegativeQty?: boolean;
  /** Переміщення: мінусові видно, але не обираються */
  movementPickerMode?: boolean;
  /** Приховати автоматично сформовані Dilovod-партії (лише звичайне комплектування) */
  hideAutoGeneratedBatches?: boolean;
  onSelect: (batch: BatchNumber) => void | Promise<void>;
  onClose: () => void;
  /** Примусово оновити партії з Dilovod (скинути серверний кеш) */
  onRefresh: () => void;
  inputRef?: React.RefObject<HTMLInputElement>;
  overlayZClassName?: string;
  /**
   * Коли picker вкладений у вже відкритий Drawer — вимкнути lock скролу,
   * щоб unlock при закритті не конфліктував із батьківським overlay.
   */
  shouldBlockScroll?: boolean;
}

/**
 * Drawer компонент для вибору партії (bottom sheet)
 * Показує список доступних партій з залишками по складах
 */
export const BatchNumbersAutocomplete = ({
  batches,
  isOpen,
  isLoading,
  selectedBatch,
  selectedStorage,
  selectedDateTime,
  sourceStorage,
  sourceStorageName,
  includeAllStorages = false,
  addedBatchKeys,
  portionsPerBox,
  includeNonPositiveQty = false,
  includeNegativeQty = false,
  movementPickerMode = false,
  hideAutoGeneratedBatches = false,
  onSelect,
  onClose,
  onRefresh,
  inputRef,
  overlayZClassName,
  shouldBlockScroll = true,
}: BatchNumbersAutocompleteProps) => {
  const { isDebugMode } = useDebug();
  const displayDate = selectedDateTime ?? new Date();
  const dateStr = displayDate.toLocaleDateString('uk-UA', { day: '2-digit', month: '2-digit', year: 'numeric' });
  const timeStr = displayDate.toLocaleTimeString('uk-UA', { hour: '2-digit', minute: '2-digit' });
  const storageHint = includeAllStorages
    ? 'складах готової продукції та малому складі'
    : `складі ${sourceStorageName || sourceStorage || 'Готової продукції'}`;

  const visibleBatches = useMemo(() => {
    if (movementPickerMode || includeNegativeQty) {
      return batches.filter((batch) => batch.quantity !== 0);
    }
    return batches;
  }, [batches, movementPickerMode, includeNegativeQty]);

  /** Закриття після вибору — після onSelect і в наступному кадрі (анти click-through). */
  const closeAfterSelect = () => {
    if (inputRef?.current) {
      inputRef.current.blur();
    }
    requestAnimationFrame(() => {
      onClose();
    });
  };

  const handlePickBatch = async (batch: BatchNumber) => {
    if (movementPickerMode && batch.quantity <= 0) return;
    // Важливо await: async onSelect (ReleaseSets тощо) має завершитись,
    // поки editingBatchIndex / activeSku ще валідні.
    await Promise.resolve(onSelect(batch));
    closeAfterSelect();
  };

  return (
    <Drawer aria-label="Виберіть партію" isOpen={isOpen} onOpenChange={(open) => {
      if (!open) {
        // Коли Drawer закривається, видаляємо фокус з input щоб не тригерити onFocus знову
        if (inputRef?.current) {
          inputRef.current.blur();
        }
        onClose();
      }
    }} size="sm" placement="right" shouldBlockScroll={shouldBlockScroll} classNames={{
      wrapper: overlayZClassName,
      backdrop: overlayZClassName,
    }}>
      <DrawerContent>
        {(onCloseDrawer) => (
          <>
            <DrawerHeader className="flex flex-col gap-1">
              <div className="flex items-center justify-between gap-2">
                <div className="flex items-center gap-2">
                  <DynamicIcon name="box" size={20} className="text-gray-400" />
                  <h2 className="text-lg font-semibold text-gray-900">Виберіть партію</h2>
                </div>
              </div>
            </DrawerHeader>

            <DrawerBody className="overflow-y-auto">
								<p className="text-sm font-normal text-gray-600 mb-3">
	                {movementPickerMode
	                  ? <>Партії з ненульовим залишком на <b>{storageHint}</b> на <b>{dateStr}, {timeStr}</b>. Мінусові показані для контролю — їх не можна обрати для переміщення.</>
	                  : includeNonPositiveQty
	                  ? <>Усі партії каталогу (включно з нульовими та мінусовими залишками) на <b>{storageHint}</b> на <b>{dateStr}, {timeStr}</b>.</>
	                  : <>Партії з залишками на <b>{storageHint}</b> доступні на <b>{dateStr}, {timeStr}</b></>}
	                {hideAutoGeneratedBatches && ' Автоматично сформовані партії приховано.'}
	              </p>
              {isLoading ? (
                <div className="flex flex-col items-center justify-center py-12 gap-3">
                  <div className="animate-spin">
                    <DynamicIcon name="loader-circle" size={32} className="text-blue-500" />
                  </div>
                  <p className="text-gray-600">Завантаження партій...</p>
                </div>
              ) : visibleBatches.length > 0 ? (
                <div className="space-y-3 pb-4">
                  {visibleBatches.map((batch, index) => {
                    const isSelected = (
                      (selectedBatch === batch.batchNumber || selectedBatch === batch.batchId)
                      && selectedStorage === batch.storage
                    );
                    const isNonSelectableNegative = movementPickerMode && batch.quantity < 0;
                    const isAlreadyAdded = addedBatchKeys?.has(`${batch.batchId}:${batch.storage}`) ?? false;
                    const isProdOrderVirtual = isProductionOrderVirtualBatch({
                      batchId: batch.batchId,
                      batchNumber: batch.batchNumber,
                    });
                    const stockBreakdown = portionsPerBox != null && portionsPerBox > 0
                      ? breakdownStockPortions(batch.quantity, portionsPerBox)
                      : null;
                    return (
                      <motion.button
                        key={`${batch.batchId}:${batch.storage}`}
                        initial={{ opacity: 0, y: 10 }}
                        animate={{ opacity: 1, y: 0 }}
                        transition={{ delay: index * 0.03 }}
                        disabled={isAlreadyAdded || isNonSelectableNegative}
                        onClick={() => {
                          if (isAlreadyAdded || isNonSelectableNegative) return;
                          void handlePickBatch(batch);
                        }}
                        className={`w-full px-4 py-4 text-left rounded-lg transition-all border-1 ${
                          isAlreadyAdded || isNonSelectableNegative
                            ? 'border-gray-200 bg-gray-50 opacity-60 cursor-not-allowed'
                            : isSelected
                            ? 'border-blue-500 bg-blue-50'
                            : isProdOrderVirtual
                            ? 'border-amber-300 bg-amber-50/60 hover:bg-amber-50'
                            : 'border-gray-200 bg-white hover:bg-gray-50'
                        }`}
                      >
                        <div className="flex items-start gap-2">
                          <div className="flex flex-col gap-2 w-full">
                            <div className="flex items-start gap-2 flex-wrap">
                              <span className="font-semibold text-gray-900">
                                {batch.batchNumber}
                                {isDebugMode && batch.batchId && (
                                  <span className="ml-1.5 font-mono text-xs font-normal text-default-400">
                                    · {batch.batchId}
                                  </span>
                                )}
                              </span>
                              {isSelected && (
                                <DynamicIcon name="check-circle" size={18} className="text-blue-600 shrink-0" />
                              )}
                              {isAlreadyAdded && (
                                <span className="text-xs font-medium text-amber-600 bg-amber-100 px-2 py-0.5 rounded-full shrink-0">
                                  Вже додано
                                </span>
                              )}
                              {isNonSelectableNegative && (
                                <span className="text-xs font-medium text-red-700 bg-red-100 px-2 py-0.5 rounded-full shrink-0">
                                  Мінус — не для переміщення
                                </span>
                              )}
                              {isProdOrderVirtual && (
                                <span
                                  className="text-[10px] font-medium uppercase tracking-wide text-amber-800 bg-amber-100 px-1.5 py-0.5 rounded shrink-0"
                                  title={PRODUCTION_ORDER_BATCH_WARNING}
                                >
                                  Без надходження
                                </span>
                              )}
                            </div>
                            <div className="flex items-center gap-1 text-sm">
                              <DynamicIcon name="warehouse" size={14} className={resolveStorageIconClass(batch.storage)} />
                              <span className="text-gray-600">{batch.storageDisplayName || 'невідомий склад'}</span>
                            </div>
                            {isProdOrderVirtual && (
                              <p className="text-xs text-amber-700 leading-snug">{PRODUCTION_ORDER_BATCH_WARNING}</p>
                            )}
                          </div>
                          <div className="flex flex-col items-end gap-1 w-28">
                            <span className={`font-semibold text-lg ${batch.quantity < 0 ? 'text-red-600' : 'text-blue-600'}`}>
                              {batch.quantity} <span className="text-xs font-light">шт.</span>
                            </span>
                            {stockBreakdown && (
                              <QtyPills boxes={stockBreakdown.boxes} loose={stockBreakdown.loosePortions} />
                            )}
                          </div>
                        </div>
                      </motion.button>
                    );
                  })}
                </div>
              ) : (
                <div className="flex flex-col items-center justify-center py-12 gap-3">
                  <DynamicIcon name="inbox" size={32} className="text-gray-300" />
                  <p className="text-gray-600 text-center">
                    Партії не знайдені для цього товару
                  </p>
                </div>
              )}
            </DrawerBody>

            <DrawerFooter className="gap-2">
              <Button
                variant="light"
                onPress={onRefresh}
                title="Оновити залишки з Dilovod"
                className="text-gray-400 hover:text-blue-500 hover:bg-blue-100!"
                startContent={<DynamicIcon name="refresh-cw" size={16} className={isLoading ? 'animate-spin' : ''} />}
              >
                Оновити залишки
              </Button>
              <Button
                color="default"
                variant="bordered"
                className="flex-1"
                onPress={() => {
                  if (inputRef?.current) {
                    inputRef.current.blur();
                  }
                  onClose();
                }}
              >
                Закрити
              </Button>
            </DrawerFooter>
          </>
        )}
      </DrawerContent>
    </Drawer>
  );
};