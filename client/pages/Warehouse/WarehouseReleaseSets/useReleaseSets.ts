function getBomPerSetQuantity(componentsSnapshot: unknown, sku: string): number {
  if (!Array.isArray(componentsSnapshot)) return 1;

  for (const component of componentsSnapshot) {
    const componentSku = String(component?.id ?? component?.sku ?? component?.code ?? '').trim();
    if (componentSku !== sku) continue;
    const quantity = Number(component?.quantity ?? component?.qty ?? NaN);
    if (Number.isFinite(quantity) && quantity > 0) return quantity;
  }

  return 1;
}

function getBatchStockLimit(batch: ReleaseComponentBatch): number {
  if (typeof batch.batchStock === 'number' && Number.isFinite(batch.batchStock) && batch.batchStock >= 0) {
    return batch.batchStock;
  }

  return Number.POSITIVE_INFINITY;
}

function deriveSetQuantityFromComponentBatches(
  componentBatches: ReleaseComponentAllocation[],
  componentsSnapshot: unknown,
): number | null {
  const candidates: number[] = [];

  for (const allocation of componentBatches) {
    const allocated = (allocation.batches ?? []).reduce(
      (sum, batch) => sum + Number(batch.quantity ?? 0),
      0,
    );
    if (allocated <= 0) continue;

    const perSet = getBomPerSetQuantity(componentsSnapshot, allocation.sku);
    if (perSet <= 0) continue;

    candidates.push(allocated / perSet);
  }

  if (candidates.length === 0) return null;

  const derived = Math.min(...candidates);
  if (!Number.isFinite(derived) || derived <= 0) return null;

  return derived;
}

function syncComponentBatchesForSetQuantity(
  componentBatches: ReleaseComponentAllocation[],
  componentsSnapshot: unknown,
  newSetQuantity: number,
  oldSetQuantity?: number | null,
): ReleaseComponentAllocation[] {
  if (newSetQuantity <= 0 || componentBatches.length === 0) {
    return componentBatches;
  }

  const scaleFactor = oldSetQuantity && oldSetQuantity > 0
    ? newSetQuantity / oldSetQuantity
    : null;

  return componentBatches.map((allocation) => {
    const perSet = getBomPerSetQuantity(componentsSnapshot, allocation.sku);
    const newRequired = perSet * newSetQuantity;
    const batches = [...(allocation.batches ?? [])];
    if (batches.length === 0) return allocation;

    const oldAllocated = batches.reduce((sum, batch) => sum + Number(batch.quantity ?? 0), 0);
    if (newRequired <= 0) {
      return { ...allocation, batches: [] };
    }

    const scaled = batches.map((batch) => {
      const batchStock = getBatchStockLimit(batch);
      const raw = scaleFactor !== null
        ? Number(batch.quantity ?? 0) * scaleFactor
        : oldAllocated > 0
          ? (Number(batch.quantity ?? 0) * newRequired) / oldAllocated
          : 0;
      return {
        ...batch,
        quantity: Math.min(batchStock, Math.max(0, Math.round(raw))),
      };
    });

    let diff = newRequired - scaled.reduce((sum, batch) => sum + batch.quantity, 0);
    if (diff !== 0) {
      const adjustable = scaled
        .map((batch, index) => ({ batch, index }))
        .sort((left, right) => {
          const leftRoom = getBatchStockLimit(left.batch) - left.batch.quantity;
          const rightRoom = getBatchStockLimit(right.batch) - right.batch.quantity;
          return diff > 0 ? rightRoom - leftRoom : left.batch.quantity - right.batch.quantity;
        });

      for (const { index } of adjustable) {
        if (diff === 0) break;
        const batch = scaled[index];
        const stock = getBatchStockLimit(batch);
        if (diff > 0) {
          const add = Math.min(diff, stock - batch.quantity);
          if (add <= 0) continue;
          scaled[index] = { ...batch, quantity: batch.quantity + add };
          diff -= add;
        } else {
          const remove = Math.min(-diff, batch.quantity);
          if (remove <= 0) continue;
          scaled[index] = { ...batch, quantity: batch.quantity - remove };
          diff += remove;
        }
      }
    }

    return {
      ...allocation,
      batches: scaled.filter((batch) => batch.quantity > 0),
    };
  });
}

function buildSingleBatchAllocation(
  sku: string,
  batch: { batchId: string; batchNumber: string; quantity: number },
  componentsSnapshot: unknown,
  setQuantity: number,
): ReleaseComponentAllocation | null {
  const batchStock = Math.max(0, Number(batch.quantity ?? 0));
  if (!batch.batchId || batchStock <= 0) return null;

  const perSet = getBomPerSetQuantity(componentsSnapshot, sku);
  const required = perSet * setQuantity;

  return {
    sku,
    batches: [{
      batchId: batch.batchId,
      batchNumber: batch.batchNumber,
      quantity: Math.min(batchStock, required),
      batchStock,
    }],
  };
}

async function fetchComponentBatchesBySku(
  skus: string[],
  options: {
    storageId?: string | null;
    firmId?: string | null;
    asOfDate?: string | null;
  },
): Promise<Record<string, Array<{ batchId: string; batchNumber: string; quantity: number }>>> {
  if (skus.length === 0) return {};

  const url = new URL('/api/warehouse/batch-numbers', window.location.origin);
  url.searchParams.set('skus', skus.join(','));
  if (options.firmId) url.searchParams.set('firmId', String(options.firmId));
  if (options.storageId) url.searchParams.set('storageId', String(options.storageId));
  if (options.asOfDate) url.searchParams.set('asOfDate', options.asOfDate);

  const response = await fetch(url.toString(), { credentials: 'include' });
  if (!response.ok) return {};

  const json = await response.json().catch(() => null) as {
    success?: boolean;
    batchesBySku?: Record<string, Array<{ batchId: string; batchNumber: string; quantity: number }>>;
  } | null;

  if (!json?.success || !json.batchesBySku) return {};
  return json.batchesBySku;
}

function buildSingleBatchPrefillAllocations(
  setItem: ReleaseSetItem,
  batchesBySku: Record<string, Array<{ batchId: string; batchNumber: string; quantity: number }>>,
): ReleaseComponentAllocation[] {
  const components = Array.isArray(setItem.componentsSnapshot) ? setItem.componentsSnapshot : [];
  const setQuantity = Number(setItem.quantity ?? 1);
  const allocations: ReleaseComponentAllocation[] = [];

  for (const component of components) {
    const sku = String(component?.id ?? component?.sku ?? component?.code ?? '').trim();
    if (!sku) continue;

    const selectable = (batchesBySku[sku] ?? []).filter((batch) => {
      const label = String(batch.batchNumber ?? batch.batchId ?? '').trim();
      return !isAutoGeneratedSystemBatch(label) && Number(batch.quantity ?? 0) > 0;
    });

    if (selectable.length !== 1) continue;

    const allocation = buildSingleBatchAllocation(
      sku,
      selectable[0],
      setItem.componentsSnapshot,
      setQuantity,
    );
    if (allocation) allocations.push(allocation);
  }

  return allocations;
}

