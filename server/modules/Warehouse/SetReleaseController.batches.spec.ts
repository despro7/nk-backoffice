import { describe, expect, it } from 'vitest';
import { __releaseControllerTesting } from './SetReleaseController.js';

const { extractComponentBatchesFromReleaseRecord } = __releaseControllerTesting;

const component_batches = [
  {
    sku: '03021',
    batches: [
      { batchId: '1112200000002125', batchNumber: '60925', quantity: 5 },
      { batchId: '1110800000003575', batchNumber: '24.09.2026 Розукомплектування 0000878', quantity: 3 },
    ],
  },
];

describe('extractComponentBatchesFromReleaseRecord', () => {
  it('у сесії коригування лишає «Розукомплектування …» (інакше PATCH їх губить)', () => {
    const result = extractComponentBatchesFromReleaseRecord({
      items: [{ component_batches }],
      correctionSessionId: 'session-1',
    });
    expect(result[0].batches.map((batch) => batch.batchNumber)).toEqual([
      '60925',
      '24.09.2026 Розукомплектування 0000878',
    ]);
  });

  it('бере сесію з items[0].correction_session_id', () => {
    const result = extractComponentBatchesFromReleaseRecord({
      items: [{ component_batches, correction_session_id: 'session-1' }],
    });
    expect(result[0].batches).toHaveLength(2);
  });

  it('поза коригуванням системні партії відфільтровуються, як і раніше', () => {
    const result = extractComponentBatchesFromReleaseRecord({ items: [{ component_batches }] });
    expect(result[0].batches.map((batch) => batch.batchNumber)).toEqual(['60925']);
  });

  it('excludeAutoGenerated: true примусово ховає їх навіть у сесії', () => {
    const result = extractComponentBatchesFromReleaseRecord({
      items: [{ component_batches }],
      correctionSessionId: 'session-1',
      excludeAutoGenerated: true,
    });
    expect(result[0].batches).toHaveLength(1);
  });
});
