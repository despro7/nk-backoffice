function getOtherAllocatedQuantity(batches: ReleaseComponentBatch[], excludeIndex: number): number {
  return batches.reduce((sum, batch, batchIndex) => {
    if (batchIndex === excludeIndex) return sum;
    return sum + Number(batch.quantity ?? 0);
  }, 0);
}

function getBatchStockLimit(
  batch: ReleaseComponentBatch,
  sourceBatches: BatchNumber[],
  allowNegativeStock = false,
): number {
  if (typeof batch.batchStock === 'number' && Number.isFinite(batch.batchStock)) {
    if (allowNegativeStock || batch.batchStock >= 0) {
      return batch.batchStock;
    }
  }

  const source = sourceBatches.find((item) => item.batchId === batch.batchId);
  const fromSource = Number(source?.quantity ?? NaN);
  if (Number.isFinite(fromSource) && (allowNegativeStock || fromSource >= 0)) {
    return fromSource;
  }

  return Number.POSITIVE_INFINITY;
}

/** Фактичний залишок по обліку (включно з мінусами) для відображення в рядку партії. */
function getAccountingBatchStock(
  batch: ReleaseComponentBatch,
  sourceBatches: BatchNumber[],
): number | null {
  if (typeof batch.batchStock === 'number' && Number.isFinite(batch.batchStock)) {
    return batch.batchStock;
  }
  const source = sourceBatches.find((item) => item.batchId === batch.batchId);
  const fromSource = Number(source?.quantity ?? NaN);
  return Number.isFinite(fromSource) ? fromSource : null;
}

function getSuggestedBatchQuantity(
  batchStock: number,
  requiredQuantity: number,
  otherAllocated: number,
  limitByStockOnly = false,
  allowNegativeStock = false,
  freeQuantityMode = false,
): number {
  if (freeQuantityMode) {
    return 0;
  }

  if (requiredQuantity <= 0) {
    if (allowNegativeStock && batchStock < 0) {
      return Math.abs(batchStock);
    }
    return batchStock > 0 ? batchStock : 0;
  }

  const remainingNeeded = Math.max(0, requiredQuantity - otherAllocated);
  if (remainingNeeded <= 0) return 0;

  if (limitByStockOnly) {
    if (allowNegativeStock && batchStock < 0) {
      return Math.min(remainingNeeded, Math.abs(batchStock));
    }
    return batchStock > 0 ? Math.min(batchStock, remainingNeeded) : 0;
  }

  if (batchStock <= 0 && !allowNegativeStock) return 0;
  if (allowNegativeStock && batchStock < 0) {
    return Math.min(remainingNeeded, Math.abs(batchStock));
  }
  return Math.min(batchStock, remainingNeeded);
}

function getBatchQuantityMax(
  batch: ReleaseComponentBatch,
  requiredQuantity: number,
  otherAllocated: number,
  sourceBatches: BatchNumber[],
  limitByStockOnly = false,
  allowUnlimitedQuantity = false,
  freeQuantityMode = false,
): number {
  if (freeQuantityMode) {
    const batchStock = getBatchStockLimit(batch, sourceBatches, false);
    return Number.isFinite(batchStock) ? Math.max(0, batchStock) : Number.POSITIVE_INFINITY;
  }

  if (allowUnlimitedQuantity) {
    return Math.max(0, requiredQuantity - otherAllocated);
  }

  const batchStock = getBatchStockLimit(batch, sourceBatches, limitByStockOnly);
  if (limitByStockOnly) {
    return Number.isFinite(batchStock) ? Math.max(0, batchStock) : Number.POSITIVE_INFINITY;
  }

  const remainingNeeded = Math.max(0, requiredQuantity - otherAllocated);
  return Math.min(batchStock, remainingNeeded);
}

function getAllocationMap(allocations: ReleaseComponentAllocation[]): Map<string, ReleaseComponentBatch[]> {
  const map = new Map<string, ReleaseComponentBatch[]>();
  for (const allocation of allocations) {
    map.set(allocation.sku, allocation.batches ?? []);
  }
  return map;
}

function filterSelectableWarehouseBatches(
  batches: BatchNumber[],
  hideAutoGeneratedBatches: boolean,
  allowNonPositiveQty: boolean,
): BatchNumber[] {
  return batches.filter((batch) => {
    const label = String(batch.batchNumber ?? batch.batchId ?? '').trim();
    if (hideAutoGeneratedBatches && isAutoGeneratedSystemBatch(label)) return false;
    // Віртуальні document-партії показуємо — потрібні для коригування/зведення залишків.
    if (!allowNonPositiveQty && Number(batch.quantity ?? 0) <= 0) return false;
    return true;
  });
}

function hasUnselectedWarehouseBatches(
  selected: ReleaseComponentBatch[],
  available: BatchNumber[],
): boolean {
  const selectedIds = new Set(selected.map((batch) => batch.batchId));
  return available.some((batch) => !selectedIds.has(batch.batchId));
}

/** Bulk-партії без enrichment expiration (FIFO сортує за номером; менше getObject у Dilovod). */
function buildReleaseBulkBatchNumbersUrl(
  skus: string[],
  options: {
    firmId?: string | null;
    storageId?: string | null;
    selectedDateTime?: Date | null;
    includeNonPositiveQty?: boolean;
  },
): URL {
  const url = new URL('/api/warehouse/batch-numbers', window.location.origin);
  url.searchParams.set('skus', skus.join(','));
  url.searchParams.set('skipExpiration', 'true');
  if (options.firmId) url.searchParams.set('firmId', options.firmId);
  if (options.storageId) url.searchParams.set('storageId', options.storageId);
  if (options.selectedDateTime) {
    url.searchParams.set('asOfDate', options.selectedDateTime.toISOString());
  }
  if (options.includeNonPositiveQty) {
    url.searchParams.set('includeNonPositiveQty', 'true');
  }
  return url;
}

async function fetchBarcodeForBatch(sku: string, batchId: string): Promise<string | null> {
  const url = new URL('/api/warehouse/barcode-for-batch', window.location.origin);
  url.searchParams.set('sku', sku);
  url.searchParams.set('batchId', batchId);

  try {
    const response = await fetch(url.toString(), { credentials: 'include' });
    if (!response.ok) return null;
    const data = await response.json().catch(() => null) as { success?: boolean; barcode?: string | null } | null;
    if (!data || data.success === false) return null;
    const barcode = String(data.barcode ?? '').trim();
    return barcode || null;
  } catch {
    return null;
  }
}

export default function ReleaseComponentBatchesPanel({
  components,
  componentBatches,
  onChange,
  selectedDateTime,
  firmId,
  storageId,
  storageName,
  readOnly = false,
  operationKey = 'goodKit',
  correctionMode = false,
  correctionStep = null,
  onFillAllBatches,
  showSectionHeading = true,
  freeQuantityMode = false,
  wrapInCard = true,
  onRemoveComponent,
  overlayZClassName,
  batchPickerShouldBlockScroll = true,
}: Props) {
  const { batches, loading, fetchBatches } = useBatchNumbers();
  const [activeSku, setActiveSku] = useState<string | null>(null);
  const [editingBatchIndex, setEditingBatchIndex] = useState<number | null>(null);
  const [deleteConfirm, setDeleteConfirm] = useState<{ sku: string; index: number; batchNumber: string } | null>(null);
  const [removeComponentConfirm, setRemoveComponentConfirm] = useState<{ sku: string; name: string } | null>(null);
  const [isDrawerOpen, setIsDrawerOpen] = useState(false);
  const [fifoLoading, setFifoLoading] = useState(false);
  const [warehouseBatchesBySku, setWarehouseBatchesBySku] = useState<Record<string, BatchNumber[]>>({});
  const inputRef = useRef<HTMLInputElement>(null);
  const barcodeFetchAttemptedRef = useRef<Set<string>>(new Set());
  const autoSelectBatchKeyRef = useRef<string | null>(null);

  const allocationMap = useMemo(() => getAllocationMap(componentBatches), [componentBatches]);
  const isCorrectionUnkitStep = correctionMode && correctionStep === 2;
  const limitByStockOnly = correctionMode && !isCorrectionUnkitStep;
  const allowNegativeBatches = isCorrectionUnkitStep;
  const hideAutoGeneratedBatches = operationKey === 'goodKit' && !correctionMode;

  const selectableBatches = useMemo(
    () => batches.filter((batch) => {
      if (hideAutoGeneratedBatches && isAutoGeneratedSystemBatch(batch.batchNumber)) {
        return false;
      }
      return true;
    }),
    [batches, hideAutoGeneratedBatches],
  );

  /** Автопідстановка лише з catalogs.goodParts — віртуальні обирає користувач вручну. */
  const autoSelectableBatches = useMemo(
    () => selectableBatches.filter((batch) => canSetTpGoodsGoodPart({
      batchId: batch.batchId,
      batchNumber: batch.batchNumber,
    })),
    [selectableBatches],
  );

  const activePortionsPerBox = useMemo(() => {
    if (!activeSku) return null;
    const component = components.find((item) => item.sku === activeSku);
    if (!component?.portionsPerBox || component.portionsPerBox <= 0) return null;
    return component.portionsPerBox;
  }, [activeSku, components]);

  const componentSkusKey = useMemo(
    () => [...new Set(components.map((component) => component.sku.trim()).filter(Boolean))].sort().join(','),
    [components],
  );

  const asOfDateKey = selectedDateTime?.getTime() ?? null;

  useEffect(() => {
    if (readOnly || !componentSkusKey) {
      setWarehouseBatchesBySku({});
      return;
    }

    let cancelled = false;
    void (async () => {
      try {
        // У correction (особливо unkit) тягнемо й мінусові залишки — для «По обліку» і автопідстановки.
        const url = buildReleaseBulkBatchNumbersUrl(componentSkusKey.split(','), {
          firmId,
          storageId,
          selectedDateTime,
          includeNonPositiveQty: allowNegativeBatches || correctionMode,
        });

        const response = await fetch(url.toString(), { credentials: 'include' });
        const json = await response.json().catch(() => null) as {
          success?: boolean;
          batchesBySku?: Record<string, BatchNumber[]>;
        } | null;

        if (cancelled || !response.ok || !json?.success || !json.batchesBySku) return;
        setWarehouseBatchesBySku(json.batchesBySku);
      } catch {
        if (!cancelled) setWarehouseBatchesBySku({});
      }
    })();

    return () => {
      cancelled = true;
    };
  }, [
    allowNegativeBatches,
    asOfDateKey,
    componentSkusKey,
    correctionMode,
    firmId,
    readOnly,
    selectedDateTime,
    storageId,
  ]);

  // Синхронізуємо batchStock з балансом складу (дата / склад / фірма → свіжі qty).
  useEffect(() => {
    if (readOnly || Object.keys(warehouseBatchesBySku).length === 0 || componentBatches.length === 0) {
      return;
    }

    let anyChanged = false;
    const next = componentBatches.map((allocation) => {
      const warehouse = warehouseBatchesBySku[allocation.sku] ?? [];
      if (warehouse.length === 0) return allocation;
      const stockById = new Map(
        warehouse.map((batch) => [batch.batchId, Number(batch.quantity ?? NaN)] as const),
      );
      let allocationChanged = false;
      const batches = (allocation.batches ?? []).map((batch) => {
        const stock = stockById.get(batch.batchId);
        if (stock == null || !Number.isFinite(stock)) return batch;
        if (batch.batchStock === stock) return batch;
        allocationChanged = true;
        anyChanged = true;
        return { ...batch, batchStock: stock };
      });
      return allocationChanged ? { ...allocation, batches } : allocation;
    });

    if (anyChanged) onChange(next);
  }, [warehouseBatchesBySku, componentBatches, onChange, readOnly]);

  useEffect(() => {
    const missing: Array<{ sku: string; batchId: string }> = [];
    for (const allocation of componentBatches) {
      for (const batch of allocation.batches ?? []) {
        const key = `${allocation.sku}::${batch.batchId}`;
        if (String(batch.barcode ?? '').trim()) {
          barcodeFetchAttemptedRef.current.delete(key);
          continue;
        }
        if (!batch.batchId) continue;
        // Після масового fill партії замінюються без ШК — дозволяємо повторний запит.
        barcodeFetchAttemptedRef.current.delete(key);
        missing.push({ sku: allocation.sku, batchId: batch.batchId });
      }
    }
    if (missing.length === 0) return;

    let cancelled = false;
    void (async () => {
      const barcodeByKey = new Map<string, string>();
      await Promise.all(missing.map(async ({ sku, batchId }) => {
        const key = `${sku}::${batchId}`;
        try {
          const barcode = await fetchBarcodeForBatch(sku, batchId);
          if (barcode) barcodeByKey.set(key, barcode);
        } finally {
          barcodeFetchAttemptedRef.current.add(key);
        }
      }));
      if (cancelled || barcodeByKey.size === 0) return;

      const next = componentBatches.map((allocation) => {
        const batches = (allocation.batches ?? []).map((batch) => {
          const key = `${allocation.sku}::${batch.batchId}`;
          const barcode = barcodeByKey.get(key);
          if (!barcode || String(batch.barcode ?? '').trim()) return batch;
          return { ...batch, barcode };
        });
        return { ...allocation, batches };
      });

      onChange(next);
    })();

    return () => {
      cancelled = true;
    };
  }, [componentBatches, onChange]);

  const updateSkuBatches = (sku: string, nextBatches: ReleaseComponentBatch[]) => {
    const others = componentBatches.filter((allocation) => allocation.sku !== sku);
    if (nextBatches.length === 0) {
      onChange(others);
      return;
    }
    onChange([...others, { sku, batches: nextBatches }]);
  };

  const openDrawer = (sku: string, batchIndex: number | null) => {
    autoSelectBatchKeyRef.current = null;
    setActiveSku(sku);
    setEditingBatchIndex(batchIndex);
    setIsDrawerOpen(true);
    void fetchBatches(
      sku,
      selectedDateTime ?? new Date(),
      firmId ?? undefined,
      false,
      storageId ?? undefined,
      { includeNonPositiveQty: allowNegativeBatches },
    );
  };

  const handleBatchSelect = async (batch: BatchNumber) => {
    // Фіксуємо до будь-якого await — onClose/rAF не повинен зіпсувати replace.
    const sku = activeSku;
    const editIdx = editingBatchIndex;
    if (!sku) return;

    const current = [...(allocationMap.get(sku) ?? [])];
    const component = components.find((row) => row.sku === sku);
    const barcode = await fetchBarcodeForBatch(sku, batch.batchId);
    const duplicate = current.some(
      (item, index) => index !== editIdx && item.batchId === batch.batchId,
    );
    if (duplicate) {
      ToastService.show({
        title: 'Партія вже додана',
        description: `Партія ${batch.batchNumber} вже є в списку`,
        color: 'warning',
      });
      setIsDrawerOpen(false);
      setEditingBatchIndex(null);
      setActiveSku(null);
      return;
    }

    const batchStock = allowNegativeBatches
      ? Number(batch.quantity ?? 0)
      : Math.max(0, Number(batch.quantity ?? 0));
    const isNewBatch = editIdx === -1 || editIdx === null;

    if (isNewBatch) {
      const otherAllocated = getOtherAllocatedQuantity(current, -1);
      const suggestedQuantity = component
        ? getSuggestedBatchQuantity(
          batchStock,
          component.requiredQuantity,
          otherAllocated,
          limitByStockOnly,
          allowNegativeBatches,
          freeQuantityMode,
        )
        : Math.max(0, batchStock);

      current.push({
        batchId: batch.batchId,
        batchNumber: batch.batchNumber,
        quantity: suggestedQuantity,
        batchStock,
        barcode: barcode ?? undefined,
      });
    } else {
      const otherAllocated = getOtherAllocatedQuantity(current, editIdx);
      const maxQuantity = component
        ? getBatchQuantityMax(
          { batchId: batch.batchId, quantity: 0, batchStock },
          component.requiredQuantity,
          otherAllocated,
          [],
          limitByStockOnly,
          isCorrectionUnkitStep,
          freeQuantityMode,
        )
        : Math.max(0, batchStock);
      const previousQuantity = Number(current[editIdx]?.quantity ?? 0);

      current[editIdx] = {
        ...current[editIdx],
        batchId: batch.batchId,
        batchNumber: batch.batchNumber,
        batchStock,
        barcode: barcode ?? undefined,
        quantity: Math.min(previousQuantity, maxQuantity),
      };
    }

    updateSkuBatches(sku, current);
    setIsDrawerOpen(false);
    setEditingBatchIndex(null);
    setActiveSku(null);
    autoSelectBatchKeyRef.current = null;
  };

  useEffect(() => {
    if (correctionMode || operationKey !== 'goodKit') return;
    if (!isDrawerOpen || !activeSku || loading || editingBatchIndex !== -1) return;
    if (autoSelectableBatches.length !== 1) return;

    const batch = autoSelectableBatches[0];
    const attemptKey = `${activeSku}:${batch.batchId}`;
    if (autoSelectBatchKeyRef.current === attemptKey) return;
    autoSelectBatchKeyRef.current = attemptKey;

    void handleBatchSelect(batch);
  }, [correctionMode, operationKey, isDrawerOpen, activeSku, loading, editingBatchIndex, autoSelectableBatches]);

  const handleQuantityChange = (sku: string, index: number, quantity: number, max?: number) => {
    const current = [...(allocationMap.get(sku) ?? [])];
    if (!current[index]) return;
    const clamped = max !== undefined
      ? Math.max(0, Math.min(max, quantity))
      : Math.max(0, quantity);
    current[index] = { ...current[index], quantity: clamped };
    updateSkuBatches(sku, current);
  };

  const handleDeleteBatch = () => {
    if (!deleteConfirm) return;
    const current = [...(allocationMap.get(deleteConfirm.sku) ?? [])];
    current.splice(deleteConfirm.index, 1);
    updateSkuBatches(deleteConfirm.sku, current);
    setDeleteConfirm(null);
  };

  const handleRemoveComponentConfirm = () => {
    if (!removeComponentConfirm || !onRemoveComponent) return;
    onRemoveComponent(removeComponentConfirm.sku);
    setRemoveComponentConfirm(null);
  };

  const handleAddAllBatchesForSku = async (sku: string) => {
    const available = filterSelectableWarehouseBatches(
      warehouseBatchesBySku[sku] ?? [],
      hideAutoGeneratedBatches,
      allowNegativeBatches,
    ).filter((batch) => canSetTpGoodsGoodPart({
      batchId: batch.batchId,
      batchNumber: batch.batchNumber,
    }));

    if (available.length === 0) {
      ToastService.show({
        title: 'Партій не знайдено',
        description: 'На складі немає доступних партій з позитивним залишком',
        color: 'warning',
      });
      return;
    }

    const current = [...(allocationMap.get(sku) ?? [])];
    const selectedIds = new Set(current.map((batch) => batch.batchId));
    const next = [...current];

    for (const batch of available) {
      if (selectedIds.has(batch.batchId)) continue;
      const batchStock = Math.max(0, Number(batch.quantity ?? 0));
      if (batchStock <= 0 && !allowNegativeBatches) continue;
      const barcode = await fetchBarcodeForBatch(sku, batch.batchId);
      next.push({
        batchId: batch.batchId,
        batchNumber: batch.batchNumber,
        quantity: batchStock,
        batchStock,
        barcode: barcode ?? undefined,
      });
      selectedIds.add(batch.batchId);
    }

    if (next.length === current.length) {
      ToastService.show({
        title: 'Партій не знайдено',
        description: 'Усі доступні партії вже додані',
        color: 'warning',
      });
      return;
    }

    updateSkuBatches(sku, next);
  };

  const handleFifoSelect = async () => {
    if (fifoLoading || readOnly || components.length === 0) return;

    const skus = [...new Set(components.map((component) => component.sku.trim()).filter(Boolean))];
    if (skus.length === 0) return;

    setFifoLoading(true);
    try {
      const url = buildReleaseBulkBatchNumbersUrl(skus, {
        firmId,
        storageId,
        selectedDateTime,
        includeNonPositiveQty: allowNegativeBatches,
      });

      const response = await fetch(url.toString(), { credentials: 'include' });
      const json = await response.json().catch(() => null) as {
        success?: boolean;
        error?: string;
        batchesBySku?: Record<string, BatchNumber[]>;
      } | null;

      if (!response.ok || !json?.success || !json.batchesBySku) {
        throw new Error(json?.error || 'Не вдалося завантажити партії');
      }

      setWarehouseBatchesBySku(json.batchesBySku);

      const now = selectedDateTime ?? new Date();
      const next: ReleaseComponentAllocation[] = [];
      const shortfall: string[] = [];

      for (const component of components) {
        const selectable = (json.batchesBySku[component.sku] ?? []).filter((batch) => {
          const label = String(batch.batchNumber ?? batch.batchId ?? '').trim();
          if (hideAutoGeneratedBatches && isAutoGeneratedSystemBatch(label)) return false;
          if (!canSetTpGoodsGoodPart({ batchId: batch.batchId, batchNumber: batch.batchNumber })) return false;
          return Number(batch.quantity ?? 0) > 0;
        });

        const allocated = allocateBatchesFifo(selectable, component.requiredQuantity, now);
        const covered = allocated.reduce((sum, batch) => sum + batch.quantity, 0);
        if (component.requiredQuantity > 0 && covered + 0.0001 < component.requiredQuantity) {
          shortfall.push(component.name || component.sku);
        }
        if (allocated.length === 0) continue;

        next.push({
          sku: component.sku,
          batches: allocated.map((batch) => ({
            batchId: batch.batchId,
            batchNumber: batch.batchNumber,
            quantity: batch.quantity,
            batchStock: batch.batchStock,
          })),
        });
      }

      onChange(next);

      if (next.length === 0) {
        ToastService.show({
          title: 'Партій не знайдено',
          description: 'На складі немає доступних партій для автовибору',
          color: 'warning',
        });
        return;
      }

      if (shortfall.length > 0) {
        ToastService.show({
          title: 'FIFO: не вистачило залишку',
          description: shortfall.join(', '),
          color: 'warning',
        });
        return;
      }

      ToastService.show({
        title: 'Партії обрано за FIFO',
        description: 'Старіші партії підставлені першими',
        color: 'success',
      });
    } catch (error) {
      ToastService.show({
        title: 'Не вдалося обрати партії',
        description: error instanceof Error ? error.message : 'Невідома помилка',
        color: 'danger',
      });
    } finally {
      setFifoLoading(false);
    }
  };

  const addedBatchKeys = new Set<string>();
  if (activeSku) {
    const rows = allocationMap.get(activeSku) ?? [];
    rows.forEach((batch, index) => {
      // Поточну редаговану партію можна «замінити» на іншу — не блокуємо її ключ як «вже додано».
      if (editingBatchIndex !== null && editingBatchIndex !== -1 && index === editingBatchIndex) {
        return;
      }
      addedBatchKeys.add(`${batch.batchId}:${storageId ?? ''}`);
    });
  }

  const showBulkFillActions = correctionMode
    && correctionStep === 1
    && Boolean(onFillAllBatches);
  const showPerSkuFillAll = freeQuantityMode;

  if (components.length === 0) return null;

  const panelBody = (
    <>
        {!correctionMode && !freeQuantityMode && (
          <Button
            size="lg"
            variant="flat"
            color="success"
            data-btn-tone="success-flat"
            className="mb-4 py-3 h-auto border-1 border-success-500/20 data-[pressed=true]:scale-[0.99] flex-wrap"
            isLoading={fifoLoading}
            spinner={<Spinner size="sm" color="success" />}
            isDisabled={readOnly || fifoLoading}
            onPress={() => {
              void handleFifoSelect();
            }}
            endContent={<span className="text-sm">(старіші партії йдуть першими)</span>}
            disableRipple={true}
          >
            Обрати партії автоматично за FIFO алгоритмом
          </Button>
        )}
        <div className="space-y-3">
          {components.map((component) => {
            const skuBatches = allocationMap.get(component.sku) ?? [];
            const allocated = skuBatches.reduce((sum, batch) => sum + Number(batch.quantity ?? 0), 0);
            const isComplete = !freeQuantityMode
              && Math.abs(allocated - component.requiredQuantity) < 0.0001;
            const stockLimitBySku = limitByStockOnly || freeQuantityMode;
            const warehouseStockTotal = (warehouseBatchesBySku[component.sku] ?? []).reduce(
              (sum, batch) => sum + Math.max(0, Number(batch.quantity ?? 0)),
              0,
            );
            const displayStockTotal = component.catalogStockAtStorage != null
              && Number.isFinite(component.catalogStockAtStorage)
              ? Math.max(component.catalogStockAtStorage, warehouseStockTotal)
              : warehouseStockTotal;
            const portionsPerBoxLabel = component.portionsPerBox != null && component.portionsPerBox > 0
              ? component.portionsPerBox
              : 1;
            const availableSkuBatches = filterSelectableWarehouseBatches(
              warehouseBatchesBySku[component.sku] ?? [],
              hideAutoGeneratedBatches,
              allowNegativeBatches,
            );
            const hasAlternativeBatches = hasUnselectedWarehouseBatches(skuBatches, availableSkuBatches);
            const canSwapSingleBatch = !correctionMode
              && hasAlternativeBatches
              && skuBatches.length === 1
              && (freeQuantityMode || isComplete);
            const canSwapBatchInRow = !correctionMode
              && hasAlternativeBatches
              && skuBatches.length > 1
              && (freeQuantityMode || isComplete);
            const canAddAnotherBatch = availableSkuBatches.length > 0 && hasAlternativeBatches;
            const showFillAllForSku = availableSkuBatches.length > 1;

            return (
              <div key={component.sku} className="overflow-hidden rounded-md border border-gray-200">
                <div className="flex flex-wrap items-start justify-between gap-2 px-3 py-2.5">
                  <div>
                    <div className="font-medium text-gray-900">{component.name || component.sku}</div>
                    <div className="text-xs text-gray-500">
                      SKU: {component.sku}
                      {freeQuantityMode && (
                        <>
                          <span className="text-gray-400"> · </span>
                          В коробці: <span className="font-semibold tabular-nums text-gray-700">{formatPortionQty(portionsPerBoxLabel)}</span> пор.
                          {(component.catalogStockGp != null || component.catalogStockMs != null || displayStockTotal > 0) && (
                            <>
                              <span className="text-gray-400"> · </span>
                              <span className="inline-flex flex-wrap items-center gap-x-1 gap-y-0.5">
                                На складі
                                <StockBadge variant="gp" size="10px" className="mx-0.5" />
                                <span className="font-semibold tabular-nums text-gray-700">
                                  {formatPortionQty(component.catalogStockGp ?? displayStockTotal)}
                                </span>
                                пор.
                                <span className="text-gray-400 mx-0.5">·</span>
                                <StockBadge variant="ms" size="10px" className="mx-0.5" />
                                <span className="font-semibold tabular-nums text-gray-700">
                                  {formatPortionQty(component.catalogStockMs ?? 0)}
                                </span>
                                пор.
                              </span>
                            </>
                          )}
                        </>
                      )}
                    </div>
                  </div>
                  <div className="flex items-center gap-1">
                    <div className="flex gap-2 items-center">

                      {component.perSetQuantity != null && (
                        <div className="mt-1 text-xs text-gray-600">
                          В наборі: <strong>{formatPortionQty(component.perSetQuantity)} шт.</strong> / разом: <strong>{formatPortionQty(component.requiredQuantity)} шт.</strong>
                        </div>
                      )}
                      
                      {!correctionMode && !freeQuantityMode && (
                      <div className="flex flex-col mr-2">
                        <span className={`flex items-center text-base font-bold ${freeQuantityMode || isComplete ? 'text-gray-800' : 'text-red-500'}`}>
                          {formatPortionQty(component.requiredQuantity)}
                        </span>
                        <span className="text-xs text-gray-400">Потрібно</span>
                      </div>
                      )}

                      <div className="flex flex-col">
                        <span className={`flex items-center gap-3.5 font-bold ${freeQuantityMode ? 'text-xl' : 'text-base'} ${freeQuantityMode || isComplete ? 'text-gray-800' : 'text-red-500'}`}>
                          {formatPortionQty(allocated)}
                          {correctionMode || freeQuantityMode ? (
                            (() => {
                              const portionsPerBox = component.portionsPerBox != null && component.portionsPerBox > 0
                                ? component.portionsPerBox
                                : 1;
                              const { boxes, loosePortions } = breakdownStockPortions(allocated, portionsPerBox);
                              return (
                                <QtyPills boxes={boxes} loose={loosePortions} />
                              );
                            })()
                          ) : null}
                        </span>
                        {!freeQuantityMode && <span className="text-xs text-gray-400">Обрано</span>}
                      </div>

                    </div>
                    {!readOnly && onRemoveComponent && (
                      <Button
                        variant="light"
                        color="danger"
                        isIconOnly
                        aria-label="Видалити товар"
                        onPress={() => setRemoveComponentConfirm({
                          sku: component.sku,
                          name: component.name || component.sku,
                        })}
                        className="ml-2.5 mr-2"
                      >
                        <DynamicIcon name="trash-2" className="h-4.5 w-4.5" />
                      </Button>
                    )}
                  </div>
                </div>

                {skuBatches.length > 0 && (
                  <div className="space-y-2 border-t border-gray-200/75 p-3">
                    {skuBatches.map((batch, index) => {
                      const otherAllocated = getOtherAllocatedQuantity(skuBatches, index);
                      const maxQuantity = getBatchQuantityMax(
                        batch,
                        component.requiredQuantity,
                        otherAllocated,
                        batches,
                        stockLimitBySku,
                        isCorrectionUnkitStep,
                        freeQuantityMode,
                      );
                      const currentQuantity = Number(batch.quantity ?? 0);
                      const batchStock = getBatchStockLimit(batch, batches, allowNegativeBatches);
                      const isBatchStockMax = !isCorrectionUnkitStep
                        && Number.isFinite(batchStock)
                        && batchStock > 0
                        && currentQuantity >= batchStock;
                      const remainingForBatch = Math.max(0, component.requiredQuantity - otherAllocated);
                      const canSetBatchMaxUnkit = isCorrectionUnkitStep
                        && !isComplete
                        && remainingForBatch > 0
                        && currentQuantity < remainingForBatch;
                      const canSetBatchMaxStock = limitByStockOnly
                        && Number.isFinite(batchStock)
                        && batchStock > 0
                        && currentQuantity < batchStock;
                      const canSetBatchMaxFree = freeQuantityMode
                        && Number.isFinite(batchStock)
                        && batchStock > 0
                        && currentQuantity < batchStock;
                      const canSetBatchMax = canSetBatchMaxUnkit || canSetBatchMaxStock || canSetBatchMaxFree;

                      const barcodeLabel = String(batch.barcode ?? '').trim();
                      const accountingStock = getAccountingBatchStock(
                        batch,
                        [
                          ...(warehouseBatchesBySku[component.sku] ?? []),
                          ...(activeSku === component.sku ? batches : []),
                        ],
                      );
                      const isProdOrderVirtual = isProductionOrderVirtualBatch({
                        batchId: batch.batchId,
                        batchNumber: batch.batchNumber,
                      });

                      return (
                      <div key={`${component.sku}-${batch.batchId}-${index}`} className="flex flex-wrap items-center gap-3 rounded-md pl-3 pr-2 py-2 bg-gray-100">
                        <div className="min-w-[140px] flex-1">
                          <div className="flex flex-wrap items-center gap-2">
                            <div className="text-sm font-medium text-gray-800">{batch.batchNumber || batch.batchId}</div>
                            {isProdOrderVirtual && (
                              <span
                                className="text-[10px] font-medium uppercase tracking-wide text-amber-800 bg-amber-100 px-1.5 py-0.5 rounded"
                                title={PRODUCTION_ORDER_BATCH_WARNING}
                              >
                                Без надходження
                              </span>
                            )}
                          </div>
                          <div className="text-xs text-gray-500">
                            ШК: <span className="font-mono text-gray-600">{barcodeLabel || '—'}</span>
                            {accountingStock != null && (
                              <>
                                {' · '}
                                По обліку:{' '}
                                <span
                                  className={`font-semibold tabular-nums ${
                                    accountingStock < 0 ? 'text-danger' : 'text-gray-600'
                                  }`}
                                >
                                  {formatPortionQty(accountingStock)}
                                </span>
                              </>
                            )}
                          </div>
                          {isProdOrderVirtual && (
                            <div className="mt-1 text-xs text-amber-700">{PRODUCTION_ORDER_BATCH_WARNING}</div>
                          )}
                        </div>
                        <div className="flex items-center gap-2">
                          <ReleaseBatchMovementsButton
                            sku={component.sku}
                            productName={component.name}
                            batchId={batch.batchId}
                            batchLabel={batch.batchNumber || batch.batchId}
                            storageId={storageId}
                          />
                          {!correctionMode && isBatchStockMax && (
                            <span className="text-xs font-medium uppercase tracking-wide text-fuchsia-700/60 bg-fuchsia-300/15 px-1.5 py-0.5 rounded">
                              max
                            </span>
                          )}
                          {canSetBatchMax && (
                            <button
                              type="button"
                              className="text-xs font-medium uppercase tracking-wide text-fuchsia-700/80 bg-fuchsia-300/15 px-1.5 py-0.5 rounded hover:bg-fuchsia-300/25"
                              onClick={() => handleQuantityChange(
                                component.sku,
                                index,
                                canSetBatchMaxUnkit
                                  ? remainingForBatch
                                  : batchStock,
                                maxQuantity,
                              )}
                            >
                              max
                            </button>
                          )}
                          <StepperInput
                            aria-label="Кількість"
                            value={currentQuantity}
                            max={maxQuantity}
                            onChange={(value) => handleQuantityChange(component.sku, index, value, maxQuantity)}
                            onIncrement={() => handleQuantityChange(component.sku, index, currentQuantity + 1, maxQuantity)}
                            onDecrement={() => handleQuantityChange(component.sku, index, Math.max(0, currentQuantity - 1), maxQuantity)}
                            size="sm"
                            className="w-32"
                            disabled={readOnly}
                          />
                        </div>
                        {!readOnly && (
                          <div className="flex items-center gap-0.5">
                            {canSwapBatchInRow && (
                              <Button
                                variant="light"
                                color="primary"
                                isIconOnly
                                aria-label="Змінити партію"
                                onPress={() => openDrawer(component.sku, index)}
                              >
                                <DynamicIcon name="edit-2" className="h-4 w-4" />
                              </Button>
                            )}
                            <Button
                              variant="light"
                              color="secondary"
                              isIconOnly
                              aria-label="Видалити партію"
                              onPress={() => setDeleteConfirm({
                                sku: component.sku,
                                index,
                                batchNumber: batch.batchNumber || batch.batchId,
                              })}
                            >
                              <DynamicIcon name="trash-2" className="h-4 w-4" />
                            </Button>
                          </div>
                        )}
                      </div>
                      );
                    })}
                  </div>
                )}

                {!readOnly && (
                  <div className="flex flex-wrap gap-2 border-t border-gray-200/75 p-3">
                    <Button
                      size="sm"
                      variant="flat"
                      color="primary"
                      data-btn-tone="primary-blue-flat"
                      className="px-3 min-w-12 gap-1 data-[disabled=true]:opacity-50"
                      startContent={<DynamicIcon name="plus" className="h-4 w-4" />}
                      isDisabled={
                        !canAddAnotherBatch
                        || (!correctionMode && !freeQuantityMode && isComplete)
                      }
                      onPress={() => openDrawer(component.sku, -1)}
                    >
                      Додати партію
                    </Button>
                    {canSwapSingleBatch ? (
                      <Button
                        size="sm"
                        variant="flat"
                        color="warning"
                        startContent={<DynamicIcon name="repeat" className="h-4 w-4" />}
                        onPress={() => openDrawer(component.sku, 0)}
                      >
                        Замінити партію
                      </Button>
                    ) : null}
                    {showBulkFillActions && showFillAllForSku && (
                      <Button
                        size="sm"
                        color="success"
                        variant="flat"
                        className="design:btn-success-flat px-3 min-w-12 gap-1"
                        startContent={<DynamicIcon name="plus-circle" className="h-4 w-4" />}
                        onPress={onFillAllBatches}
                      >
                        Додати всі партії
                      </Button>
                    )}
                    {showPerSkuFillAll && showFillAllForSku && (
                      <Button
                        size="sm"
                        color="success"
                        variant="flat"
                        className="design:btn-success-flat px-3 min-w-12 gap-1"
                        startContent={<DynamicIcon name="plus-circle" className="h-4 w-4" />}
                        onPress={() => {
                          void handleAddAllBatchesForSku(component.sku);
                        }}
                      >
                        Додати всі партії
                      </Button>
                    )}
                  </div>
                )}
              </div>
            );
          })}
        </div>
    </>
  );

  return (
    <>
      {showSectionHeading && (
        <div className="mb-2 flex items-center justify-between gap-3">
          <h3 className="font-medium text-gray-800">Компоненти набору</h3>
          <span className="text-xs text-gray-500">Місце зберігання: <b>{storageName ?? storageId ?? '—'}</b></span>
        </div>
      )}

      {wrapInCard ? (
        <Card className={`rounded-xl border border-gray-200 bg-white p-4 ${showSectionHeading ? 'mb-6' : 'mb-0'}`}>
          {panelBody}
        </Card>
      ) : (
        <div className={showSectionHeading ? 'mb-6' : 'mb-0'}>
          {panelBody}
        </div>
      )}

      <BatchNumbersAutocomplete
        batches={selectableBatches}
        isOpen={isDrawerOpen}
        isLoading={loading}
        selectedBatch={
          editingBatchIndex !== null
          && editingBatchIndex !== -1
          && activeSku
            ? (allocationMap.get(activeSku)?.[editingBatchIndex]?.batchNumber ?? '')
            : ''
        }
        selectedStorage={storageId ?? ''}
        selectedDateTime={selectedDateTime ?? new Date()}
        sourceStorage={storageId ?? undefined}
        sourceStorageName={storageName ?? undefined}
        addedBatchKeys={addedBatchKeys}
        portionsPerBox={activePortionsPerBox}
        includeNonPositiveQty={allowNegativeBatches}
        hideAutoGeneratedBatches={hideAutoGeneratedBatches}
        onSelect={handleBatchSelect}
        onClose={() => {
          setIsDrawerOpen(false);
          setEditingBatchIndex(null);
          setActiveSku(null);
        }}
        onRefresh={() => {
          if (!activeSku) return;
          void fetchBatches(
            activeSku,
            selectedDateTime ?? new Date(),
            firmId ?? undefined,
            true,
            storageId ?? undefined,
            { includeNonPositiveQty: allowNegativeBatches },
          );
        }}
        inputRef={inputRef}
        overlayZClassName={overlayZClassName}
        shouldBlockScroll={batchPickerShouldBlockScroll}
      />

      <ConfirmModal
        isOpen={Boolean(deleteConfirm)}
        title="Видалити партію з операції?"
        message={deleteConfirm ? `Партія ${deleteConfirm.batchNumber} буде видалена з поточної операції.` : ''}
        confirmText="Видалити"
        cancelText="Скасувати"
        confirmColor="danger"
        onConfirm={handleDeleteBatch}
        onCancel={() => setDeleteConfirm(null)}
        overlayZClassName={overlayZClassName}
      />

      <ConfirmModal
        isOpen={Boolean(removeComponentConfirm)}
        title="Видалити товар з реєстру?"
        message={removeComponentConfirm
          ? `«${removeComponentConfirm.name}» буде прибрано з поточної операції разом із обраними партіями.`
          : ''}
        confirmText="Видалити"
        cancelText="Скасувати"
        confirmColor="danger"
        onConfirm={handleRemoveComponentConfirm}
        onCancel={() => setRemoveComponentConfirm(null)}
        overlayZClassName={overlayZClassName}
      />
    </>
  );
}
