/** PATCH /api/warehouse/releases/:id — редагування запису + синхронізація з Dilovod */
router.patch('/:id', authenticateToken, warehouseOperate, async (req, res) => {
  try {
    const id = Number(req.params.id);
    if (!Number.isFinite(id) || id <= 0) {
      return res.status(400).json({ success: false, error: 'Invalid id' });
    }

    const existing = await prisma.warehouseReleaseSet.findUnique({ where: { id } });
    if (!existing || existing.status === 'deleted') {
      return res.status(404).json({ success: false, error: 'Not found' });
    }
    if (existing.status !== RELEASE_STATUS_CREATED && existing.status !== RELEASE_STATUS_SEND_FAILED) {
      return res.status(422).json({ success: false, error: 'Редагувати можна лише активні операції комплектування' });
    }

    assertCanEditReleaseRecord(req, existing);

    const bodyItems = Array.isArray(req.body?.items) ? req.body.items : null;
    const fullSnapshot = Boolean(bodyItems && bodyItems.length > 0);
    const userId = Number((req as any).user?.userId || (req as any).user?.id) || null;

    let nextOperDate = req.body?.operDate != null
      ? (parseLocalDate(req.body.operDate) ?? parseLocalDate(req.body?.date) ?? existing.operDate)
      : (parseLocalDate(req.body?.date) ?? existing.operDate);
    let nextComment = req.body?.comment !== undefined
      ? (req.body.comment == null || String(req.body.comment).trim() === '' ? null : String(req.body.comment).trim())
      : existing.comment;
    let nextQuantity = req.body?.quantity != null
      ? Math.max(0, Math.trunc(Number(req.body.quantity)))
      : existing.quantity;
    let nextSetSku = req.body?.setSku !== undefined
      ? (req.body.setSku == null || String(req.body.setSku).trim() === '' ? null : String(req.body.setSku).trim())
      : existing.setSku;
    let nextStorageId = existing.storageId;
    let nextFirmId = existing.firmId;
    let nextOperationType = existing.operationType;
    let nextItems: any[] = Array.isArray(existing.items) ? [...existing.items] : [];
    let parsedBatches: ReturnType<typeof parseComponentBatches> = [];

    if (fullSnapshot && bodyItems) {
      parsedBatches = parseComponentBatches(req.body?.componentBatches, {
        excludeAutoGenerated: shouldExcludeAutoGeneratedBatches(req.body?.correctionSessionId),
      });
      const historyPayload = await prepareReleaseHistoryPayload({
        items: bodyItems,
        componentBatches: parsedBatches,
        remark: req.body?.remark,
        comment: req.body?.comment,
        operationType: req.body?.operationType ?? existing.operationType,
        operDate: req.body?.operDate ?? req.body?.date ?? existing.operDate,
        correctionSessionId: req.body?.correctionSessionId,
      });
      nextOperDate = historyPayload.resolvedOperDate;
      nextComment = historyPayload.historyComment;
      nextQuantity = historyPayload.totalQuantity;
      nextSetSku = historyPayload.setSku;
      nextOperationType = historyPayload.resolvedOperationType;
      nextStorageId = req.body?.storageId != null && String(req.body.storageId).trim() !== ''
        ? String(req.body.storageId).trim()
        : existing.storageId;
      nextFirmId = req.body?.firmId != null && String(req.body.firmId).trim() !== ''
        ? String(req.body.firmId).trim()
        : existing.firmId;
      nextItems = preserveReleaseItemMeta(existing.items, historyPayload.itemsWithNames);
      if (nextItems[0] && typeof nextItems[0] === 'object') {
        (nextItems[0] as Record<string, unknown>).component_batches = parsedBatches;
      }
    }

    const before = {
      operDate: existing.operDate,
      comment: existing.comment,
      quantity: existing.quantity,
      setSku: existing.setSku,
      batches: summarizeReleaseBatches(existing.items),
      storageId: existing.storageId,
      firmId: existing.firmId,
    };
    const after = {
      operDate: nextOperDate,
      comment: nextComment,
      quantity: nextQuantity,
      setSku: nextSetSku,
      batches: summarizeReleaseBatches(nextItems),
      storageId: nextStorageId,
      firmId: nextFirmId,
    };
    const changes = buildReleaseUpdateDiff(before, after);
    if (changes.length === 0 && nextOperationType === existing.operationType) {
      return res.json({ success: true, data: existing, unchanged: true });
    }

    const editorLabel = await getReleaseEditorLabel(userId);
    const remarkNote = buildWarehouseReleaseEditRemarkNote(editorLabel, changes);

    if (!fullSnapshot && nextItems[0] && typeof nextItems[0] === 'object') {
      nextItems[0] = {
        ...(nextItems[0] as Record<string, unknown>),
        quantity: nextQuantity,
        set_sku: nextSetSku,
        setSku: nextSetSku,
      };
    }

    if (existing.status === RELEASE_STATUS_CREATED && existing.dilovodDocId) {
      const syncItems = fullSnapshot && bodyItems
        ? bodyItems.map((item: any, index: number) => (
          index === 0
            ? {
              ...item,
              component_batches: parsedBatches,
              ...(Array.isArray(existing.items) && existing.items[0] && typeof existing.items[0] === 'object'
                ? { kit_output_batch: (existing.items[0] as { kit_output_batch?: unknown }).kit_output_batch }
                : {}),
            }
            : item
        ))
        : nextItems;
      const syncResult = await syncWarehouseReleaseToDilovod({
        record: {
          ...existing,
          items: syncItems,
          storageId: nextStorageId,
          firmId: nextFirmId,
          operationType: nextOperationType,
        },
        operDate: nextOperDate,
        quantity: nextQuantity,
        setSku: nextSetSku,
        remarkNote,
      });
      if (!syncResult.success) {
        return res.status(422).json({ success: false, error: syncResult.error || 'Не вдалося оновити документ у Dilovod' });
      }
      if (syncResult.remark && nextItems[0] && typeof nextItems[0] === 'object') {
        nextItems[0] = {
          ...(nextItems[0] as Record<string, unknown>),
          dilovod_remark: syncResult.remark,
        };
      }
    }

    const updated = await prisma.warehouseReleaseSet.update({
      where: { id },
      data: {
        operDate: nextOperDate,
        comment: nextComment,
        quantity: nextQuantity,
        setSku: nextSetSku,
        storageId: nextStorageId,
        firmId: nextFirmId,
        operationType: nextOperationType,
        items: nextItems,
      },
    });

    await warehouseReleaseAuditService.log({
      releaseId: id,
      action: 'release_updated',
      userId,
      payload: { changes } as Prisma.InputJsonValue,
    });

    return res.json({ success: true, data: updated });
  } catch (error) {
    const message = error instanceof Error ? error.message : 'Internal server error';
    const status = message.includes('недоступне') ? 403 : 500;
    console.error('[SetRelease] patch release error:', error);
    return res.status(status).json({ success: false, error: message });
  }
});

