function preserveBatchBarcodes(
  nextBatches: ReleaseComponentBatch[],
  previousAllocations: ReleaseComponentAllocation[],
  sku: string,
): ReleaseComponentBatch[] {
  const previousByBatchId = new Map<string, string>();
  for (const batch of previousAllocations.find((allocation) => allocation.sku === sku)?.batches ?? []) {
    const barcode = String(batch.barcode ?? '').trim();
    if (barcode) {
      previousByBatchId.set(batch.batchId, barcode);
    }
  }

  return nextBatches.map((batch) => {
    const barcode = String(batch.barcode ?? '').trim() || previousByBatchId.get(batch.batchId);
    return barcode ? { ...batch, barcode } : batch;
  });
}

function sortBatchesByStockDesc(batches: ReleaseComponentBatch[]): ReleaseComponentBatch[] {
  return [...batches].sort((left, right) => {
    const leftQty = Number(left.batchStock ?? left.quantity ?? 0);
    const rightQty = Number(right.batchStock ?? right.quantity ?? 0);
    return rightQty - leftQty;
  });
}

/** Автопідстановка (крок 2): без системних Dilovod-партій; у picker вони лишаються для ручного вибору. */
function filterAutoGeneratedReleaseBatches(
  allocations: ReleaseComponentAllocation[],
): ReleaseComponentAllocation[] {
  return allocations
    .map((allocation) => ({
      ...allocation,
      batches: (allocation.batches ?? []).filter((batch) => {
        const label = String(batch.batchNumber ?? batch.batchId ?? '').trim();
        return !isAutoGeneratedSystemBatch(label);
      }),
    }))
    .filter((allocation) => allocation.batches.length > 0);
}

function resolveSourceSkuFromSetItem(item: ReleaseSetItem | null | undefined): string | null {
  const direct = String(item?.sourceSku ?? '').trim();
  if (direct) return direct;

  const snapshot = item?.componentsSnapshot;
  if (!Array.isArray(snapshot) || snapshot.length === 0) return null;

  const first = snapshot[0];
  return String(first?.id ?? first?.sku ?? first?.code ?? '').trim() || null;
}

function buildFillBatchesAllocation(
  sku: string,
  result: FillBatchesResult,
  previousAllocations: ReleaseComponentAllocation[],
): ReleaseComponentAllocation[] {
  const batches = sortBatchesByStockDesc(
    preserveBatchBarcodes(
      dedupePositiveStockBatches(result.batches).map((batch) => {
        const batchStock = Number(batch.quantity ?? 0);
        return {
          ...batch,
          batchStock,
          quantity: batchStock,
        };
      }),
      previousAllocations,
      sku,
    ),
  );

  if (batches.length === 0) return [];
  return [{ sku, batches }];
}

function dedupePositiveStockBatches(batches: ReleaseComponentBatch[]): ReleaseComponentBatch[] {
  const seen = new Set<string>();
  const result: ReleaseComponentBatch[] = [];

  for (const batch of batches) {
    const batchId = String(batch.batchId ?? '').trim();
    const quantity = Number(batch.quantity ?? 0);
    if (!batchId || seen.has(batchId) || !Number.isFinite(quantity) || quantity <= 0) continue;
    seen.add(batchId);
    result.push({ ...batch, quantity });
  }

  return result;
}

