async function patchReleaseSendError(
  releaseId: number,
  existingItems: unknown,
  sendError: ReleaseSendErrorInfo,
): Promise<boolean> {
  if (!Array.isArray(existingItems) || existingItems.length === 0) return false;
  const nextItems = existingItems.map((item, index) => {
    if (index !== 0 || !item || typeof item !== 'object') return item;
    return {
      ...(item as Record<string, unknown>),
      dilovod_send_error: sendError,
    };
  });
  await prisma.warehouseReleaseSet.update({
    where: { id: releaseId },
    data: {
      items: nextItems as Prisma.InputJsonValue,
      status: RELEASE_STATUS_SEND_FAILED,
    },
  });
  return true;
}

